/** Captures key moments of the vertical slice at a chosen quality for visual review. */
import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { setTimeout as sleep } from 'node:timers/promises';
import fs from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const PORT = 4183, OUT = 'test-output/shots', Q = process.env.QUALITY || 'high';
fs.mkdirSync(OUT, { recursive: true });
const server = spawn('npx', ['vite', '--port', String(PORT), '--strictPort'], { stdio: 'ignore' });
for (let i = 0; i < 60; i++) { try { if ((await fetch(`http://localhost:${PORT}/`)).ok) break; } catch {} await sleep(500); }
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
page.setDefaultTimeout(180000);
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto(`http://localhost:${PORT}/?test=1&quality=${Q}`);
await page.waitForFunction(() => window.__IRON?.game?.state === 'menu', null, { timeout: 240000 });
const G = (fn, a) => page.evaluate(fn, a);
const shot = async (name) => { await G(() => new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)))); await sleep(400); await page.screenshot({ path: `${OUT}/${name}.png` }); console.log('shot', name); };
await G(() => { const g = window.__IRON.game; g.audio.init(); g.startNewCampaign(); });
await G(() => window.__IRON.game.advance(11));
await G(() => { const p = window.__IRON.game.player; p.mountYaw = 0.0; p.mountPitch = -0.12; window.__IRON.game.advance(0.05); });
await shot('a-cabin-squad');
await G(() => { const g = window.__IRON.game; g.advance(14); const p = g.player; p.mountYaw = 1.35; p.mountPitch = -0.35; g.advance(0.05); });
await shot('b-cabin-door-city');
await G(() => { const g = window.__IRON.game; const p = g.player; p.mountYaw = -0.6; p.mountPitch = -0.1; g.advance(0.05); });
await shot('c-cabin-briggs');
await G(() => { const g = window.__IRON.game; g.advance(28); const p = g.player; p.mountYaw = 1.2; p.mountPitch = -0.25; g.advance(0.05); });
await shot('d-final-approach');
await G(() => { const g = window.__IRON.game; g.advance(14); const p = g.player; p.yaw = Math.PI / 2 + Math.PI; p.pitch = -0.1; g.advance(0.05); });
await shot('e-landed-disembark');
await G(() => { const g = window.__IRON.game; const p = g.player; p.yaw = -Math.PI / 2; g.input.simulateKey('KeyW', true); for (let i = 0; i < 40 && g.mission.stage === 'disembark'; i++) g.advance(0.1); g.input.simulateKey('KeyW', false); g.advance(0.25);
  const b = g.mission.squadById.briggs; p.yaw = Math.atan2(-(b.pos.x - p.pos.x), -(b.pos.z - p.pos.z)); p.pitch = -0.3; g.advance(0.1); });
await shot('f-sniper-shot');
await G(() => { const g = window.__IRON.game; g.advance(6); const p = g.player; p.yaw = 0.05; p.pitch = 0.12; g.advance(0.05); });
await shot('g-ambush-firefight');
await G(() => { const g = window.__IRON.game; const p = g.player; p.pos.set(-2, 0, 9); p.crouched = true; p.crouchToggle = true; g.input.simulateMouseButton(2, true); g.advance(0.6); p.yaw = 0.15; p.pitch = 0.3; g.advance(0.05); });
await shot('h-ads-sniper-tower');
await G(() => { const g = window.__IRON.game; g.input.simulateMouseButton(2, false); g.saves.save({ mission: 'm01', checkpoint: 'cp_crossroads', weapons: g.weapons.serialize() }); g.restartFromCheckpoint(); g.advance(2); const p = g.player; p.yaw = 0.1; p.pitch = 0.02; g.advance(0.05); });
await shot('i-crossroads');
await G(() => { const g = window.__IRON.game; g.saves.save({ mission: 'm01', checkpoint: 'cp_halden', weapons: g.weapons.serialize() }); g.restartFromCheckpoint(); g.advance(2); const p = g.player; p.pos.set(3, 0, -140); p.yaw = 0.05; p.pitch = 0.08; g.advance(0.05); });
await shot('j-halden');
console.log('errors:', errors.length ? errors : 'none');
await browser.close(); server.kill();
